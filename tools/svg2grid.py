#!/usr/bin/env python3
"""Convert the pixel-art SVG layers in docs/icon/ into Swift pixel grids.

The SVGs are 1024x1024 with 16 px cells (a 64x64 grid) made only of <rect> elements.
Output: Packages/DDKit/Sources/DDDesign/Art/IconArt.generated.swift

Usage: python3 tools/svg2grid.py
"""
import re
import string
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CELL = 16
SIZE = 64
# Colors in the boss layer that are its eyes; the app recolors them by boss phase.
EYE_COLORS = {"e0342f"}
LAYERS = [
    ("nightSky", "docs/icon/1-background.svg", "Night sky over a city with a stone floor (Nico's icon background)."),
    ("alarmClock", "docs/icon/2-boss.svg", "The alarm-clock deadline boss (Nico's icon boss)."),
    ("sword", "docs/icon/3-sword.svg", "The hero's sword (Nico's icon sword)."),
]
KEYS = [c for c in string.ascii_letters + string.digits + "#$%&*+-:;<=>?@^_~" if c != "."]
RECT = re.compile(r'<rect x="(\d+)" y="(\d+)" width="(\d+)" height="(\d+)" fill="#([0-9a-fA-F]{6})"/>')


def convert(path):
    grid = [["." for _ in range(SIZE)] for _ in range(SIZE)]
    colors = []
    for x, y, w, h, color in RECT.findall((ROOT / path).read_text()):
        color = color.lower()
        if color not in colors:
            colors.append(color)
        key = KEYS[colors.index(color)]
        x, y, w, h = (int(v) // CELL for v in (x, y, w, h))
        for yy in range(y, y + h):
            for xx in range(x, x + w):
                grid[yy][xx] = key
    return ["".join(row) for row in grid], colors


def main():
    out = [
        "// Generated by tools/svg2grid.py from docs/icon/*.svg. Do not edit by hand.",
        "// Art by Nico Taitl (icon layers), converted to 64x64 pixel grids.",
        "",
        "extension PixelArt {",
    ]
    for name, path, doc in LAYERS:
        rows, colors = convert(path)
        key = "".join(KEYS[i] for i in range(len(colors)))
        eyes = "".join(KEYS[i] for i, c in enumerate(colors) if c in EYE_COLORS)
        out.append(f"    /// {doc}")
        out.append(f"    public static let {name} = PixelArt(")
        out.append(f'        key: "{key}",')
        out.append("        colors: [" + ", ".join(f"0x{c.upper()}" for c in colors) + "],")
        out.append(f'        eyes: "{eyes}",')
        out.append("        rows: [")
        out.extend(f'            "{r}",' for r in rows)
        out.append("        ]")
        out.append("    )")
        out.append("")
    out[-1] = "}"
    target = ROOT / "Packages/DDKit/Sources/DDDesign/Art/IconArt.generated.swift"
    target.write_text("\n".join(out) + "\n")
    print(f"wrote {target.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
